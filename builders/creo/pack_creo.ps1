# Creo Fixture Builder: pack a run folder into the zip we read back.
# Run in Windows PowerShell 5.1, after build_creo.html has written results.json in its working folder:
#   powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\pack_creo.ps1 -Folder <that folder>
# It takes each built design's newest save (p01a.prt.3 is packed as p01a.prt) and its STEP copy (packed as
# p01a.step), results.json and FixtureBuilder.log. A file that contains your user name, PC name or home folder is
# left out and named. Nothing in the folder is changed or deleted; the zip is new (-2, -3 ... when the name is taken).
param([string]$Folder = (Get-Location).Path)
# Generated by builders/gen/emit_creo.py from builders/gen/creo_pack.ps1. Do not edit.
$BUILDER_VERSION = '2026.11.24.1'
$ErrorActionPreference = 'Stop'
if ($PSVersionTable.PSEdition -eq 'Core') { throw 'Use Windows PowerShell 5.1 (powershell.exe), not PowerShell 7 (pwsh).' }
$Folder = (Resolve-Path -LiteralPath $Folder).Path
$resultsPath = [IO.Path]::Combine($Folder, 'results.json')
if (-not (Test-Path -LiteralPath $resultsPath)) { throw 'No results.json in this folder: run build_creo.html first (or save its results here).' }
$rows = @(Get-Content -LiteralPath $resultsPath -Raw -Encoding UTF8 | ConvertFrom-Json)

$Secrets = @()
foreach ($value in @($env:USERPROFILE, $env:USERNAME, $env:COMPUTERNAME)) { if ($value -and $value.Length -ge 2) { $Secrets += $value } }
function Leaks([string]$path) {
    $bytes = [IO.File]::ReadAllBytes($path)
    $ascii = [Text.Encoding]::GetEncoding(28591).GetString($bytes)
    $wide = [Text.Encoding]::Unicode.GetString($bytes)
    foreach ($secret in $Secrets) {
        if ($ascii.IndexOf($secret, [StringComparison]::OrdinalIgnoreCase) -ge 0 -or $wide.IndexOf($secret, [StringComparison]::OrdinalIgnoreCase) -ge 0) { return $true }
    }
    return $false
}
# Creo numbers each save (p01a.prt.1, p01a.prt.2 ...): the newest one is the file.
function Newest([string]$name) {
    $best = $null; $bestN = -1
    foreach ($f in (Get-ChildItem -LiteralPath $Folder -File | Where-Object { $_.Name -ieq $name -or $_.Name -like ($name + '.*') })) {
        $n = 0
        if ($f.Name.Length -gt $name.Length) { $tail = $f.Name.Substring($name.Length + 1); if (-not [int]::TryParse($tail, [ref]$n)) { continue } }
        if ($n -gt $bestN) { $best = $f; $bestN = $n }
    }
    return $best
}

$version = if ($rows.Count -and $rows[0].version) { [string]$rows[0].version } else { 'unknown' }
$build = if ($rows.Count -and $rows[0].build) { [string]$rows[0].build } else { 'unknown' }
$label = ('Creo-' + $version + '-Build-' + $build) -replace '[^A-Za-z0-9.-]+', '-'
$zipPath = [IO.Path]::Combine($Folder, $label + '.zip')
$n = 2
while (Test-Path -LiteralPath $zipPath) { $zipPath = [IO.Path]::Combine($Folder, "$label-$n.zip"); $n++ }

$entries = [ordered]@{}
foreach ($row in $rows) {
    if ($row.status -ne 'ok') { continue }
    foreach ($file in $row.files) {
        $stem = [IO.Path]::GetFileNameWithoutExtension($file)
        $source = if ($file -like '*.step') { (Newest ($stem + '.stp')), (Newest ($stem + '.step')) | Where-Object { $_ } | Select-Object -First 1 } else { Newest $file }
        if ($source) { $entries[$file] = $source.FullName } else { Write-Host "missing in the folder: $file" }
    }
}
foreach ($extra in 'results.json', 'FixtureBuilder.log') {
    $p = [IO.Path]::Combine($Folder, $extra)
    if (Test-Path -LiteralPath $p) { $entries[$extra] = $p }
}

Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
$left = @()
$zip = [IO.Compression.ZipFile]::Open($zipPath, 'Create')
try {
    foreach ($name in $entries.Keys) {
        if (Leaks $entries[$name]) { $left += $name; continue }
        # Forward slashes: the zip cmdlet of PowerShell 5.1 writes backslashes, which other unzippers misread.
        [void][IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $entries[$name], "$label/$name")
    }
} finally { $zip.Dispose() }
foreach ($name in $left) { Write-Host "left out of the zip (it contains your user or PC name): $name" }

$built = @($rows | Where-Object { $_.status -eq 'ok' }).Count
$failed = @($rows | Where-Object { $_.status -eq 'failed' }).Count
$skipped = @($rows | Where-Object { $_.status -eq 'not_scripted' }).Count
$total = $rows.Count
$shown = $zipPath
if ($env:USERPROFILE -and $zipPath.StartsWith($env:USERPROFILE + '\')) { $shown = '~' + $zipPath.Substring($env:USERPROFILE.Length) }
$plural = if ($total -eq 1) { '' } else { 's' }
Write-Host ''
Write-Host ("$total recipe$plural`: $built built, $failed failed, $skipped not scripted (details in FixtureBuilder.log).`nNext: send this zip to Dutchy in a Discord direct message:`n$shown")
