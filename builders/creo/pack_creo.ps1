# Creo numbers each save (p01a.prt.1, p01a.prt.2 ...): the newest one is the file.
function Newest([string]$name) {
    $best = $null; $bestN = -1
    foreach ($f in (Get-ChildItem -LiteralPath $Folder -File | Where-Object { $_.Name -ieq $name -or $_.Name -like ($name + '.*') })) {
        $n = 0
        if ($f.Name.Length -gt $name.Length) { $tail = $f.Name.Substring($name.Length + 1); if (-not [int]::TryParse($tail, [ref]$n)) { continue } }
        if ($n -gt $bestN) { $best = $f; $bestN = $n }
    }
    return $best
}

$version = if ($rows.Count -and $rows[0].version) { [string]$rows[0].version } else { 'unknown' }
$build = if ($rows.Count -and $rows[0].build) { [string]$rows[0].build } else { 'unknown' }
$label = ('Creo-' + $version + '-Build-' + $build) -replace '[^A-Za-z0-9.-]+', '-'
$zipPath = [IO.Path]::Combine($Folder, $label + '.zip')
$n = 2
while (Test-Path -LiteralPath $zipPath) { $zipPath = [IO.Path]::Combine($Folder, "$label-$n.zip"); $n++ }

Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
# Each built design's files, scanned raw and inflated. A design whose file names you is failed in the zipped
# results.json and none of its files go in; the files in this folder stay as they are.
$entries = [ordered]@{}
$left = @()
foreach ($row in $rows) {
    if ($row.status -ne 'ok') { continue }
    $mine = [ordered]@{}
    $leaked = @()
    foreach ($file in $row.files) {
        $stem = [IO.Path]::GetFileNameWithoutExtension($file)
        $source = if ($file -like '*.step') { (Newest ($stem + '.stp')), (Newest ($stem + '.step')) | Where-Object { $_ } | Select-Object -First 1 } else { Newest $file }
        if (-not $source) { Write-Host "missing in the folder: $file"; continue }
        # The bytes that go in the zip, scanned as they will be sent; a file that cannot be read counts as leaking.
        try { $bytes = [IO.File]::ReadAllBytes($source.FullName) } catch { $leaked += $file; continue }
        if ($file -like '*.step') { $bytes = CleanStep $bytes $file }
        if (LeaksBytes $bytes) { $leaked += $file } else { $mine[$file] = $bytes }
    }
    if ($leaked.Count) {
        $row.status = 'failed'
        $row.error = 'privacy: ' + ($leaked -join ', ') + ' contains your user folder, user or PC name (Creo writes the folder it saves in); left out of the zip. Run again in C:\Users\Public\FixtureOut.'
        $row.files = @()
        $left += $leaked
        continue
    }
    foreach ($file in $mine.Keys) { $entries[$file] = $mine[$file] }
}

$zip = [IO.Compression.ZipFile]::Open($zipPath, 'Create')
try {
    foreach ($name in $entries.Keys) {
        # Forward slashes: the zip cmdlet of PowerShell 5.1 writes backslashes, which other unzippers misread.
        $stream = $zip.CreateEntry("$label/$name").Open()
        try { $stream.Write($entries[$name], 0, $entries[$name].Length) } finally { $stream.Dispose() }
    }
    # results.json (with any privacy failures) and the log, with your user folder, user and PC name replaced.
    $texts = [ordered]@{ 'results.json' = (ConvertTo-Json -InputObject @($rows) -Depth 32) }
    $logPath = [IO.Path]::Combine($Folder, 'FixtureBuilder.log')
    if (Test-Path -LiteralPath $logPath) { $texts['FixtureBuilder.log'] = [IO.File]::ReadAllText($logPath) }
    foreach ($name in $texts.Keys) {
        $clean = Scrub $texts[$name]
        if (HitText $clean) { $left += $name; continue }
        $writer = [IO.StreamWriter]::new($zip.CreateEntry("$label/$name").Open(), [Text.UTF8Encoding]::new($false))
        try { $writer.Write($clean) } finally { $writer.Dispose() }
    }
} catch {
    # A half-written zip never stays behind to be sent by mistake.
    $zip.Dispose()
    Remove-Item -LiteralPath $zipPath -Force -ErrorAction SilentlyContinue
    throw
} finally { $zip.Dispose() }
foreach ($name in $left) { Write-Host "left out of the zip (it contains your user folder, user or PC name): $name" }

$built = @($rows | Where-Object { $_.status -eq 'ok' }).Count
$failed = @($rows | Where-Object { $_.status -eq 'failed' }).Count
$skipped = @($rows | Where-Object { $_.status -eq 'not_scripted' }).Count
$total = $rows.Count
$shown = $zipPath
if ($env:USERPROFILE -and $zipPath.StartsWith($env:USERPROFILE + '\')) { $shown = '~' + $zipPath.Substring($env:USERPROFILE.Length) }
$plural = if ($total -eq 1) { '' } else { 's' }
Write-Host ''
Write-Host ("$total recipe$plural`: $built built, $failed failed, $skipped not scripted (details in FixtureBuilder.log).`nNext: send this zip to Dutchy in a Discord direct message:`n$shown")
