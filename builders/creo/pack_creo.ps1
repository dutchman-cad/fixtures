# Creo Fixture Builder: pack a run folder into the zip we read back.
# Run in Windows PowerShell 5.1, after build_creo.html has written results.json in its working folder:
#   powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\pack_creo.ps1 -Folder <that folder>
# It takes each built design's newest save (p01a.prt.3 is packed as p01a.prt) and its STEP copy (packed as
# p01a.step), results.json and FixtureBuilder.log. Every file is scanned, raw and inside its compressed streams, for
# your user folder, OneDrive, user name and PC name: a design whose file has one is marked failed in the zipped
# results.json and left out. The log and results.json go in with those replaced (%USERPROFILE% ...). It refuses a
# folder inside your user folder or OneDrive. Nothing in the folder is changed or deleted; the zip is new (-2, -3 ...).
param([string]$Folder = (Get-Location).Path)
