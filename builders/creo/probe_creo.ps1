# One check: runs the block, records ok / failed with Creo's exact error text, never stops the probe.
function Check([string]$name, [scriptblock]$block) {
    $script:Total++
    $watch = [Diagnostics.Stopwatch]::StartNew()
    $row = [ordered]@{}
    try {
        $value = & $block
        $row.status = 'ok'
        if ($null -ne $value) { $row.value = $value }
        $script:Passed++
    } catch {
        $row.status = 'failed'
        $err = $_.Exception
        while ($err.InnerException) { $err = $err.InnerException }
        $row.error = Scrub ($err.GetType().Name + ': ' + $err.Message)
    }
    $row.seconds = [math]::Round($watch.Elapsed.TotalSeconds, 2)
    $script:Report.checks[$name] = $row
    $detail = if ($row.status -eq 'ok') { if ($row.Contains('value')) { ' ' + (($row.value | ConvertTo-Json -Compress -Depth 4)) } else { '' } } else { ' ' + $row.error }
    if ($detail.Length -gt 400) { $detail = $detail.Substring(0, 400) + '...' }
    Say ("$name " + $row.status + $detail)
    if ($row.status -eq 'ok') { return $value }
}

