$Report.passed = $Passed
$Report.total = $Total
$Report.vbapi_server = $VbServer
$Report | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $Run 'probe.json') -Encoding UTF8
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
$label = ($Release -replace '[^A-Za-z0-9.]+', '-').Trim('-')
$ZipPath = Join-Path $Run ("CreoProbe-$label.zip")
$zip = [IO.Compression.ZipFile]::Open($ZipPath, 'Create')
try {
    foreach ($file in (Get-ChildItem -LiteralPath $Run -File | Where-Object { $_.Name -ne 'run.log' -and $_.FullName -ne $ZipPath })) {
        # Raw and inflated: Creo may keep the save folder inside a compressed stream.
        if (Leaks $file.FullName) { Say ("left out of the zip (it contains your user folder, user or PC name): " + $file.Name); continue }
        [void][IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $file.FullName, "CreoProbe-$label/" + $file.Name)
    }
} catch {
    # A half-written zip never stays behind to be sent by mistake.
    $zip.Dispose()
    Remove-Item -LiteralPath $ZipPath -Force -ErrorAction SilentlyContinue
    throw
} finally { $zip.Dispose() }
$shown = $ZipPath
if ($env:USERPROFILE -and $ZipPath.StartsWith($env:USERPROFILE + '\')) { $shown = '~' + $ZipPath.Substring($env:USERPROFILE.Length) }
$finish = "Creo probe: $Passed of $Total checks passed (details in probe.log).`nNext: send this zip to Dutchy in a Discord direct message:`n$shown"
Add-Content -LiteralPath $Log -Value $finish -Encoding UTF8
Write-Host ''
