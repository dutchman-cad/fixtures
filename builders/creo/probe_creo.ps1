            foreach ($o in 'template_solidpart', 'template_designasm', 'template_sheetmetalpart', 'pro_unit_length', 'pro_unit_mass', 'intf3d_out_default_option', 'step_export_format') {
                try { $c[$o] = Scrub ($S.GetConfigOption($o)) } catch { $c[$o] = 'unreadable' }
            }
            $c
        } | Out-Null
        $P = Check 'create_part' { $S.CreatePart('cfprobe_p') }
        if ($P) {
            Check 'part_features' {
                # pfc sequences are read by index (Count, Item); they need not enumerate in PowerShell.
                $features = $P.ListFeaturesByType($false, $Missing)
                @(for ($i = 0; $i -lt $features.Count; $i++) { $features.Item($i).FeatTypeName })
            } | Out-Null
            Check 'create_feature_call' { $P.CreateFeature($null) } | Out-Null
            Check 'create_parameter' {
                $mi = New-Object -ComObject (Prog 'ModelItem')
                $param = $P.CreateParam('cf_probe_w', $mi.CreateDoubleParamValue(20.0))
                $param.Value.DoubleValue
            } | Out-Null
            Check 'save_part' { $P.Save(); @(Get-ChildItem -LiteralPath $Run -Filter 'cfprobe_p*' | ForEach-Object Name) } | Out-Null
            Check 'mass_property' { $mp = $P.GetMassProperty($Missing); [ordered]@{ volume = $mp.Volume; area = $mp.SurfaceArea } } | Out-Null
            Check 'export_step_part' {
                $P.ExportIntf3D('cfprobe_p', (EnumValue 'EpfcExportType' 'EpfcEXPORT_STEP'), $Missing)
                @(Get-ChildItem -LiteralPath $Run | Where-Object { $_.Name -like 'cfprobe_p*' -and $_.Extension -notmatch '^\.\d+$' } | ForEach-Object Name)
            } | Out-Null
            Check 'copy_part' { $copy = $P.CopyAndRetrieve('cfprobe_q', $null); $copy.Save(); $copy.FileName } | Out-Null
            $A = Check 'create_assembly' { $S.CreateAssembly('cfprobe_a') }
            if ($A) {
                Check 'assemble_component' { $feature = $A.AssembleComponent($P, $Missing); $feature.FeatTypeName } | Out-Null
                Check 'save_assembly' { $A.Save(); $A.FileName } | Out-Null
                Check 'export_step_assembly' { $A.ExportIntf3D('cfprobe_a', (EnumValue 'EpfcExportType' 'EpfcEXPORT_STEP'), $Missing); 'ok' } | Out-Null
            }
        }
    }
    Check 'end_session' { $Conn.End(); 'ended' } | Out-Null
    Start-Sleep -Seconds 3
    Check 'creo_processes_after' { [ordered]@{ before = $before; after = @(Get-Process -Name xtop -ErrorAction SilentlyContinue).Count } } | Out-Null
}

