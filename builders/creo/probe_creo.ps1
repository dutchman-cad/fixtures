                      [Environment]::GetFolderPath('MyDocuments'), [Environment]::GetFolderPath('Desktop'))) {
    if ($folder -and $folder.Length -ge 4 -and $folder -notmatch '^[A-Za-z]:[\\/]+Users[\\/]+Public([\\/]|$)') { $PersonalFolders += $folder.TrimEnd('\', '/') }
}
