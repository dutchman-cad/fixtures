# Creo Parametric probe for the Fixture Builders: what this Creo can be scripted with.
# Run once, in Windows PowerShell 5.1, with Creo closed:
#   powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\probe_creo.ps1
# It reads the install (folders, registry), loads the VB API's own type library to list what the API offers, then
# starts its own Creo session in the background, makes an empty part and assembly in a new folder, saves them,
# exports STEP and closes that session again. It never attaches to a Creo you have open and never changes an option
# file. Nothing personal is written: your user name, PC name and home folder are replaced before anything is saved,
# and a file that still contains one of them is left out of the zip.
param(
    [string]$OutputFolder = (Join-Path ([Environment]::GetFolderPath('MyDocuments')) 'CreoProbe'),
    [string]$CreoExe = '',
    [switch]$NoStart
)
# Generated by builders/gen/emit_creo.py from builders/gen/creo_probe.ps1. Do not edit.
$PROBE_VERSION = '2026.11.23.1'
$ErrorActionPreference = 'Stop'
if ($PSVersionTable.PSEdition -eq 'Core') { throw 'Use Windows PowerShell 5.1 (powershell.exe), not PowerShell 7 (pwsh).' }

$Run = $null
$n = 1
while ($true) {
    $name = if ($n -eq 1) { "probe_creo-$PROBE_VERSION" } else { "probe_creo-$PROBE_VERSION-$n" }
    $candidate = Join-Path $OutputFolder $name
    if (-not (Test-Path -LiteralPath $candidate)) { $Run = $candidate; break }
    $n++
}
New-Item -ItemType Directory -Path $Run -Force | Out-Null
$RunLog = Join-Path $Run 'run.log'
Set-Content -LiteralPath $RunLog -Value $Run -Encoding UTF8

# Privacy: the user name, PC name and home folder never reach a saved file.
$Secrets = @()
foreach ($value in @($env:USERPROFILE, $env:USERNAME, $env:COMPUTERNAME, $env:USERDOMAIN)) {
    if ($value -and $value.Length -ge 2) { $Secrets += $value }
}
$Secrets = $Secrets | Sort-Object Length -Descending
function Scrub([object]$text) {
    if ($null -eq $text) { return $null }
    $s = [string]$text
    foreach ($secret in $Secrets) {
        $label = if ($secret -eq $env:USERPROFILE) { '%USERPROFILE%' } elseif ($secret -eq $env:COMPUTERNAME) { '%COMPUTERNAME%' } else { '%USERNAME%' }
        $s = [regex]::Replace($s, [regex]::Escape($secret), $label, 'IgnoreCase')
    }
    return $s
}

$Log = Join-Path $Run 'probe.log'
function Say([string]$line) {
    $text = (Get-Date).ToString('HH:mm:ss') + ' ' + (Scrub $line)
    Add-Content -LiteralPath $Log -Value $text -Encoding UTF8
    Write-Host $text
}

$Report = [ordered]@{ probe = $PROBE_VERSION; started_utc = (Get-Date).ToUniversalTime().ToString('s') + 'Z'; checks = [ordered]@{} }
$Passed = 0
$Total = 0
# One check: runs the block, records ok / failed with Creo's exact error text, never stops the probe.
function Check([string]$name, [scriptblock]$block) {
    $script:Total++
    $watch = [Diagnostics.Stopwatch]::StartNew()
    $row = [ordered]@{}
    try {
        $value = & $block
        $row.status = 'ok'
        if ($null -ne $value) { $row.value = $value }
        $script:Passed++
    } catch {
        $row.status = 'failed'
        $err = $_.Exception
        while ($err.InnerException) { $err = $err.InnerException }
        $row.error = Scrub ($err.GetType().Name + ': ' + $err.Message)
    }
    $row.seconds = [math]::Round($watch.Elapsed.TotalSeconds, 2)
    $script:Report.checks[$name] = $row
    $detail = if ($row.status -eq 'ok') { if ($row.Contains('value')) { ' ' + (($row.value | ConvertTo-Json -Compress -Depth 4)) } else { '' } } else { ' ' + $row.error }
    if ($detail.Length -gt 400) { $detail = $detail.Substring(0, 400) + '...' }
    Say ("$name " + $row.status + $detail)
    if ($row.status -eq 'ok') { return $value }
}

Say "Creo probe $PROBE_VERSION"
Check 'windows' { [ordered]@{ os = [Environment]::OSVersion.VersionString; powershell = $PSVersionTable.PSVersion.ToString(); bit64 = [Environment]::Is64BitProcess } } | Out-Null

# 1. Installs: the uninstall entries and the PTC folders.
$Installs = Check 'installs' {
    $rows = @()
    $keys = @('HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*', 'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*')
    foreach ($entry in (Get-ItemProperty $keys -ErrorAction SilentlyContinue | Where-Object { $_.DisplayName -match 'Creo|Pro/ENGINEER|PTC' })) {
        $rows += [ordered]@{ name = $entry.DisplayName; version = $entry.DisplayVersion; folder = (Scrub $entry.InstallLocation) }
    }
    $rows
}
$Found = @()
$roots = @($env:ProgramFiles, ${env:ProgramFiles(x86)}, 'C:\PTC', 'D:\PTC', 'D:\Program Files') | Where-Object { $_ } | Select-Object -Unique
foreach ($root in $roots) {
    foreach ($base in @([IO.Path]::Combine($root, 'PTC'), $root)) {
        if (-not (Test-Path -LiteralPath $base -ErrorAction SilentlyContinue)) { continue }
        foreach ($dir in (Get-ChildItem -LiteralPath $base -Directory -ErrorAction SilentlyContinue | Where-Object { $_.Name -match '^Creo ' })) {
            $exe = [IO.Path]::Combine($dir.FullName, 'Parametric', 'bin', 'parametric.exe')
            if (Test-Path -LiteralPath $exe) { $Found += [pscustomobject]@{ Folder = $dir.FullName; Exe = $exe; Name = $dir.Name } }
        }
    }
}
$Found = @($Found | Sort-Object Folder -Unique)
Check 'creo_folders' {
    @($Found | ForEach-Object {
        $info = (Get-Item -LiteralPath $_.Exe).VersionInfo
        [ordered]@{ name = $_.Name; folder = (Scrub $_.Folder); file_version = $info.FileVersion; product_version = $info.ProductVersion }
    })
} | Out-Null
if ($CreoExe) {
    $Pick = [pscustomobject]@{ Exe = $CreoExe; Folder = (Split-Path (Split-Path (Split-Path $CreoExe))); Name = (Split-Path (Split-Path (Split-Path $CreoExe)) -Leaf) }
} elseif ($Found.Count) {
    # Newest release by its version number ("Creo 10.0.2.0" beats "Creo 9.0.5.0").
    $Pick = $Found | Sort-Object { try { [version](($_.Name -replace '^Creo\s+', '') -replace '[^0-9.]', '') } catch { [version]'0.0' } } | Select-Object -Last 1
} else {
    $Pick = $null
}
$Release = if ($Pick) { $Pick.Name } else { 'Creo-unknown' }
$Report.release = $Release
Say ("using " + $(if ($Pick) { $Pick.Exe } else { 'no Creo found' }))

# 2. API files in the picked install: VB API, Object TOOLKIT Java (J-Link), Creo.JS, Toolkit registrations, Java.
$Common = if ($Pick) { [IO.Path]::Combine($Pick.Folder, 'Common Files') } else { $null }
Check 'api_files' {
    $wanted = '^(pfcls\.exe|vb_api_register\.bat|pro_comm_msg\.exe|.*\.jar|creotk\.dat|protk\.dat|java\.exe|creojs.*|weblink.*)$'
    $hits = @()
    if (-not $Pick) { throw 'no Creo install found' }
    foreach ($place in @([IO.Path]::Combine($Pick.Folder, 'Parametric', 'bin'), $Common)) {
        if (-not (Test-Path -LiteralPath $place)) { continue }
        foreach ($file in (Get-ChildItem -LiteralPath $place -Recurse -Depth 6 -ErrorAction SilentlyContinue | Where-Object { $_.Name -match $wanted })) {
            $hits += (Scrub $file.FullName.Substring($Pick.Folder.Length + 1))
        }
    }
    @($hits | Sort-Object -Unique | Select-Object -First 300)
} | Out-Null
Check 'environment' { [ordered]@{ PRO_COMM_MSG_EXE = (Scrub $env:PRO_COMM_MSG_EXE); PRO_DIRECTORY = (Scrub $env:PRO_DIRECTORY); creo_processes = @(Get-Process -Name xtop, parametric -ErrorAction SilentlyContinue).Count } } | Out-Null

# 3. VB API registration: its COM names, server and type library.
$ProgIds = @(Check 'vbapi_progids' {
    $hkcr = [Microsoft.Win32.Registry]::ClassesRoot
    @($hkcr.GetSubKeyNames() | Where-Object { $_ -like 'pfcls.*' })
})
Say ("VB API COM names: " + $ProgIds.Count)
function Prog([string]$suffix) {
    $ProgIds | Where-Object { $_ -match ('^pfcls\.(CC|CM|M)?(pfc)?' + [regex]::Escape($suffix) + '(\.\d+)?$') } | Select-Object -First 1
}
$AsyncProg = Prog 'AsyncConnection'
$TypeLibPath = Check 'vbapi_typelib' {
    if (-not $AsyncProg) { throw 'pfcls.*AsyncConnection is not registered: the VB API is not installed or not registered (vb_api_register.bat)' }
    $hkcr = [Microsoft.Win32.Registry]::ClassesRoot
    $clsid = $hkcr.OpenSubKey("$AsyncProg\CLSID").GetValue('')
    $server = $hkcr.OpenSubKey("CLSID\$clsid\LocalServer32")
    $lib = $hkcr.OpenSubKey("CLSID\$clsid\TypeLib")
    $path = $null
    if ($lib) {
        $libId = $lib.GetValue('')
        $versions = $hkcr.OpenSubKey("TypeLib\$libId")
        foreach ($v in ($versions.GetSubKeyNames() | Sort-Object { try { [version]$_ } catch { [version]'0.0' } } -Descending)) {
            foreach ($arch in 'win64', 'win32') {
                $k = $hkcr.OpenSubKey("TypeLib\$libId\$v\0\$arch")
                if ($k) { $path = $k.GetValue(''); break }
            }
            if ($path) { break }
        }
    }
    if (-not $path -and $server) { $path = ([string]$server.GetValue('')).Trim('"') -replace '"?\s+-.*$', '' }
    $script:VbServer = if ($server) { Scrub $server.GetValue('') } else { $null }
    $path
}

# 4. The API's own list of classes, members and enum values, read from its type library.
$Enums = @{}
if ($TypeLibPath) {
    Add-Type -TypeDefinition @'
using System;
using System.Collections.Generic;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Runtime.InteropServices.ComTypes;
public class CreoProbeSink : ITypeLibImporterNotifySink {
    static Dictionary<string, Assembly> cache = new Dictionary<string, Assembly>();
    [DllImport("oleaut32.dll", CharSet = CharSet.Unicode, PreserveSig = false)]
    static extern void LoadTypeLibEx(string file, int kind, out ITypeLib library);
    public void ReportEvent(ImporterEventKind kind, int code, string message) { }
    public Assembly ResolveRef(object library) { return Convert((ITypeLib)library); }
    public static Assembly Load(string file) { ITypeLib library; LoadTypeLibEx(file, 2, out library); return Convert(library); }
    public static Assembly Convert(ITypeLib library) {
        string name = Marshal.GetTypeLibName(library);
        if (cache.ContainsKey(name)) return cache[name];
        Assembly result = new TypeLibConverter().ConvertTypeLibToAssembly(library, "Interop." + name + ".dll",
            TypeLibImporterFlags.None, new CreoProbeSink(), null, null, "Interop." + name, null);
        cache[name] = result;
        return result;
    }
}
'@
    $Api = Check 'vbapi_api_listing' {
        $assembly = [CreoProbeSink]::Load($TypeLibPath)
        $types = [ordered]@{}
        $enumCount = 0
        foreach ($t in ($assembly.GetTypes() | Sort-Object Name)) {
            if ($t.IsEnum) {
                $values = [ordered]@{}
                foreach ($m in [Enum]::GetNames($t)) { $values[$m] = [int][Enum]::Parse($t, $m) }
                $script:Enums[$t.Name] = $values
                $types[$t.Name] = $values
                $enumCount++
            } elseif ($t.IsInterface) {
                $members = @($t.GetMembers() | ForEach-Object { if ($_ -is [Reflection.MethodInfo]) { $_.Name + '/' + $_.GetParameters().Count } else { $_.Name } } | Where-Object { $_ -notmatch '^(get|set|put)_' } | Sort-Object -Unique)
                $types[$t.Name] = $members
            }
        }
        $types | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath (Join-Path $Run 'api.json') -Encoding UTF8
        [ordered]@{ types = $types.Count; enums = $enumCount; has_CreateFeature = [bool](($types['IpfcSolid']) -match '^CreateFeature/') }
    }
}
function EnumValue([string]$enum, [string]$member) {
    if ($Enums.ContainsKey($enum) -and $Enums[$enum].Contains($member)) { return $Enums[$enum][$member] }
    throw "no enum value $enum.$member in this VB API"
}
$Missing = [Reflection.Missing]::Value

# 5. A live session of our own: create, save, export STEP, assemble, copy, then close it.
$Conn = $null
if (-not $NoStart -and $Pick -and $AsyncProg) {
    if (-not $env:PRO_COMM_MSG_EXE) {
        $msg = Get-ChildItem -LiteralPath $Common -Recurse -Depth 4 -Filter 'pro_comm_msg.exe' -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($msg) { $env:PRO_COMM_MSG_EXE = $msg.FullName; Say 'set PRO_COMM_MSG_EXE for this probe only' }
    }
    $TextDir = [IO.Path]::Combine($Common, 'text')
    $before = @(Get-Process -Name xtop -ErrorAction SilentlyContinue).Count
    $Conn = Check 'start_session_no_graphics' {
        $factory = New-Object -ComObject $AsyncProg
        $factory.Start(('"' + $Pick.Exe + '" -g:no_graphics -i:rpc_input'), $TextDir)
    }
    if (-not $Conn) {
        $Conn = Check 'start_session_with_graphics' {
            $factory = New-Object -ComObject $AsyncProg
            $factory.Start(('"' + $Pick.Exe + '"'), $TextDir)
        }
    }
}
if ($Conn) {
    $S = Check 'session' { $Conn.Session }
    if (-not $S) {
        $S = Check 'session_via_GetCurrentSessionWithCompatibility' {
            $m = New-Object -ComObject (Prog 'Session')
            $m.GetCurrentSessionWithCompatibility((EnumValue 'EpfcCreoCompatibility' 'EpfcC4Compatible'))
        }
    }
    if ($S) {
        Check 'creo_version' {
            $v = [ordered]@{}
            foreach ($member in 'GetProEVersion', 'GetProEBuildCode', 'GetDisplayDateCode', 'GetReleaseNumericVersion') {
                try { $v[$member] = Scrub ($S.$member()) } catch { }
            }
            $v
        } | Out-Null
        Check 'working_folder' { $S.ChangeDirectory($Run); Scrub $S.GetCurrentDirectory() } | Out-Null
        Check 'config_options' {
            $c = [ordered]@{}
            foreach ($o in 'template_solidpart', 'template_designasm', 'template_sheetmetalpart', 'pro_unit_length', 'pro_unit_mass', 'intf3d_out_default_option', 'step_export_format') {
                try { $c[$o] = Scrub ($S.GetConfigOption($o)) } catch { $c[$o] = 'unreadable' }
            }
            $c
        } | Out-Null
        $P = Check 'create_part' { $S.CreatePart('cfprobe_p') }
        if ($P) {
            Check 'part_features' {
                # pfc sequences are read by index (Count, Item); they need not enumerate in PowerShell.
                $features = $P.ListFeaturesByType($false, $Missing)
                @(for ($i = 0; $i -lt $features.Count; $i++) { $features.Item($i).FeatTypeName })
            } | Out-Null
            Check 'create_feature_call' { $P.CreateFeature($null) } | Out-Null
            Check 'create_parameter' {
                $mi = New-Object -ComObject (Prog 'ModelItem')
                $param = $P.CreateParam('cf_probe_w', $mi.CreateDoubleParamValue(20.0))
                $param.Value.DoubleValue
            } | Out-Null
            Check 'save_part' { $P.Save(); @(Get-ChildItem -LiteralPath $Run -Filter 'cfprobe_p*' | ForEach-Object Name) } | Out-Null
            Check 'mass_property' { $mp = $P.GetMassProperty($Missing); [ordered]@{ volume = $mp.Volume; area = $mp.SurfaceArea } } | Out-Null
            Check 'export_step_part' {
                $P.ExportIntf3D('cfprobe_p', (EnumValue 'EpfcExportType' 'EpfcEXPORT_STEP'), $Missing)
                @(Get-ChildItem -LiteralPath $Run | Where-Object { $_.Name -like 'cfprobe_p*' -and $_.Extension -notmatch '^\.\d+$' } | ForEach-Object Name)
            } | Out-Null
            Check 'copy_part' { $copy = $P.CopyAndRetrieve('cfprobe_q', $null); $copy.Save(); $copy.FileName } | Out-Null
            $A = Check 'create_assembly' { $S.CreateAssembly('cfprobe_a') }
            if ($A) {
                Check 'assemble_component' { $feature = $A.AssembleComponent($P, $Missing); $feature.FeatTypeName } | Out-Null
                Check 'save_assembly' { $A.Save(); $A.FileName } | Out-Null
                Check 'export_step_assembly' { $A.ExportIntf3D('cfprobe_a', (EnumValue 'EpfcExportType' 'EpfcEXPORT_STEP'), $Missing); 'ok' } | Out-Null
            }
        }
    }
    Check 'end_session' { $Conn.End(); 'ended' } | Out-Null
    Start-Sleep -Seconds 3
    Check 'creo_processes_after' { [ordered]@{ before = $before; after = @(Get-Process -Name xtop -ErrorAction SilentlyContinue).Count } } | Out-Null
}

# 6. Privacy scan, report and zip.
$Report.passed = $Passed
$Report.total = $Total
$Report.vbapi_server = $VbServer
$Report | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $Run 'probe.json') -Encoding UTF8
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
$label = ($Release -replace '[^A-Za-z0-9.]+', '-').Trim('-')
$ZipPath = Join-Path $Run ("CreoProbe-$label.zip")
$zip = [IO.Compression.ZipFile]::Open($ZipPath, 'Create')
try {
    foreach ($file in (Get-ChildItem -LiteralPath $Run -File | Where-Object { $_.Name -ne 'run.log' -and $_.FullName -ne $ZipPath })) {
        $bytes = [IO.File]::ReadAllBytes($file.FullName)
        $ascii = [Text.Encoding]::GetEncoding(28591).GetString($bytes)
        $wide = [Text.Encoding]::Unicode.GetString($bytes)
        $leak = $false
        foreach ($secret in $Secrets) {
            if ($ascii.IndexOf($secret, [StringComparison]::OrdinalIgnoreCase) -ge 0 -or $wide.IndexOf($secret, [StringComparison]::OrdinalIgnoreCase) -ge 0) { $leak = $true }
        }
        if ($leak) { Say ("left out of the zip (it contains your user or PC name): " + $file.Name); continue }
        [void][IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $file.FullName, "CreoProbe-$label/" + $file.Name)
    }
} finally { $zip.Dispose() }
$shown = $ZipPath
if ($env:USERPROFILE -and $ZipPath.StartsWith($env:USERPROFILE + '\')) { $shown = '~' + $ZipPath.Substring($env:USERPROFILE.Length) }
$finish = "Creo probe: $Passed of $Total checks passed (details in probe.log).`nNext: send this zip to Dutchy in a Discord direct message:`n$shown"
Add-Content -LiteralPath $Log -Value $finish -Encoding UTF8
Write-Host ''
Write-Host $finish
