$Secrets = @($Secrets | Sort-Object Length -Descending)
# Words: the user name, the profile folder's own name (often not the user name: jsmith.ACME), the PC name, the domain
# and the logon server; each with the placeholder it is scrubbed to.
$Words = [ordered]@{}
$profileLeaf = if ($env:USERPROFILE) { [IO.Path]::GetFileName($env:USERPROFILE.TrimEnd('\', '/')) } else { '' }
foreach ($pair in @(@($env:USERNAME, '%USERNAME%'), @($profileLeaf, '%USERNAME%'), @($env:COMPUTERNAME, '%COMPUTERNAME%'),
                    @($env:USERDOMAIN, '%USERDOMAIN%'), @($env:LOGONSERVER, '%LOGONSERVER%'))) {
    $pattern = WordPattern $pair[0]
    if ($pattern -and -not $Words.Contains($pattern)) { $Words[$pattern] = $pair[1] }
}
# Any profile folder but Public/Default/All Users (also 8.3 names like JOSEPE~1 and JSON-escaped backslashes), any
# OneDrive, any home folder but /Users/Shared: a path that names a person.
# The drive letter is optional (files also carry \Users\<name>\ alone), either slash works.
$ProfilePattern = '(?:[A-Za-z]:)?[\\/]+(Users|Documents and Settings)[\\/]+(?!(Public|Default|All Users|Shared)([\\/"]|$))[^\\/"<>|:*?\x00\r\n]{2,64}'
$HomePattern = '/(home|Users)/(?!(Shared|Public)(/|$))[^/\x00"<>|\r\n]{1,64}'
# A network share (\\server\share): names a company or a PC.
$UncPattern = '\\\\[A-Za-z0-9._-]{2,}\\'
$PersonalPattern = $ProfilePattern + '|OneDrive|' + $HomePattern + '|' + $UncPattern

# A folder whose path names the person (their profile, OneDrive, their user or PC name).
function Personal([string]$path) {
    if (-not $path) { return $false }
    foreach ($folder in $PersonalFolders) { if ($path.StartsWith($folder, [StringComparison]::OrdinalIgnoreCase)) { return $true } }
    foreach ($secret in $Secrets) { if (($path + '\').IndexOf($secret, [StringComparison]::OrdinalIgnoreCase) -ge 0) { return $true } }
    foreach ($pattern in $Words.Keys) { if ([regex]::IsMatch($path, $pattern, 'IgnoreCase')) { return $true } }
    return [regex]::IsMatch($path, $PersonalPattern, 'IgnoreCase')
}

# Text with the person taken out. A personal path goes WHOLE, with the rest of it (C:\Users\bob\Dropbox (Acme Corp)\x
# leaves nothing of Acme), up to a quote or the end of the line; then the words. JSON-escaped paths alike.
$Tail = '(?:[^"''<>|\r\n\\]|\\(?!"))*'
function Scrub([object]$text) {
    if ($null -eq $text) { return $null }
    $s = [string]$text
    foreach ($folder in $PersonalFolders) {
        foreach ($form in @($folder, $folder.Replace('\', '\\'), $folder.Replace('\', '/'))) {
            $s = [regex]::Replace($s, [regex]::Escape($form) + $Tail, '%USERPROFILE%', 'IgnoreCase')
        }
    }
    $s = [regex]::Replace($s, $ProfilePattern + $Tail, '%USERPROFILE%', 'IgnoreCase')
    $s = [regex]::Replace($s, $HomePattern + $Tail, '/%USERPROFILE%')
    $s = [regex]::Replace($s, 'OneDrive' + $Tail, '%OneDrive%', 'IgnoreCase')
    # A network share goes whole too: \\server\share\My Part.x leaves nothing.
    $s = [regex]::Replace($s, '\\\\+[A-Za-z0-9._$-]{2,}[\\/]' + $Tail, '%SHARE%')
    if ($env:USERNAME -and $env:USERNAME.Length -ge 2) {
        $s = [regex]::Replace($s, '(?<=[\\/])' + [regex]::Escape($env:USERNAME) + '(?=[\\/])', '%USERNAME%', 'IgnoreCase')
    }
    foreach ($pattern in $Words.Keys) { $s = [regex]::Replace($s, $pattern, $Words[$pattern], 'IgnoreCase') }
    return $s
}

function HitText([string]$text) {
    foreach ($secret in $Secrets) { if ($text.IndexOf($secret, [StringComparison]::OrdinalIgnoreCase) -ge 0) { return $true } }
    foreach ($pattern in $Words.Keys) { if ([regex]::IsMatch($text, $pattern, 'IgnoreCase')) { return $true } }
    return [regex]::IsMatch($text, $PersonalPattern, 'IgnoreCase')
}
# Bytes read every way a name can be stored: Latin-1, UTF-8, this PC's ANSI code page (Cyrillic, CJK ... names), and
# UTF-16 at both byte alignments (a path at an odd offset is missed by an even-only read).
function HitBytes([byte[]]$bytes) {
    if ($bytes.Length -lt 2) { return $false }
    foreach ($encoding in @([Text.Encoding]::GetEncoding(28591), [Text.Encoding]::UTF8, [Text.Encoding]::Default)) {
        if (HitText ($encoding.GetString($bytes))) { return $true }
    }
    if (HitText ([Text.Encoding]::Unicode.GetString($bytes, 0, $bytes.Length - ($bytes.Length % 2)))) { return $true }
    return (HitText ([Text.Encoding]::Unicode.GetString($bytes, 1, ($bytes.Length - 1) - (($bytes.Length - 1) % 2))))
}
# The inflated bytes of a deflate stream starting at $at, or $null when it is not one. A stream bigger than 64 MB is
# not scanned to its end, so it throws: Leaks counts that as a hit, never as clean.
function Inflate([byte[]]$bytes, [int]$at) {
    $capped = $false
    try {
        $source = [IO.MemoryStream]::new($bytes, $at, $bytes.Length - $at)
        $inflater = [IO.Compression.DeflateStream]::new($source, [IO.Compression.CompressionMode]::Decompress)
        $out = [IO.MemoryStream]::new()
        $buffer = New-Object byte[] 65536
        while ($true) {
            $n = $inflater.Read($buffer, 0, $buffer.Length)
            if ($n -le 0) { break }
            $out.Write($buffer, 0, $n)
            if ($out.Length -ge 64MB) { $capped = $true; break }
        }
        if (-not $capped -and $out.Length -ge 16) { return ,$out.ToArray() }
    } catch { }
    if ($capped) { throw 'a compressed stream is over 64 MB: not scanned to its end' }
    return $null
}
# Where the deflate data of a zlib (78 xx), gzip (1F 8B 08) or zip entry (PK 03 04, method 8) header at $i starts.
function StreamStart([byte[]]$bytes, [int]$i) {
    $b0 = [int]$bytes[$i]; $b1 = [int]$bytes[$i + 1]
    if ($b0 -eq 0x78 -and (($b0 * 256 + $b1) % 31) -eq 0 -and ($b1 -band 0x20) -eq 0) { return $i + 2 }
    if ($b0 -eq 0x1F -and $b1 -eq 0x8B -and $bytes[$i + 2] -eq 8) { return $i + 10 }
    if ($b0 -eq 0x50 -and $b1 -eq 0x4B -and $bytes[$i + 2] -eq 3 -and $bytes[$i + 3] -eq 4 -and $bytes[$i + 8] -eq 8) {
        return $i + 30 + [int]$bytes[$i + 26] + 256 * [int]$bytes[$i + 27] + [int]$bytes[$i + 28] + 256 * [int]$bytes[$i + 29]
    }
    return -1
}
# True when the file, or any compressed stream inside it, names the person.
# Fails closed: a file that cannot be read or scanned (locked by antivirus, out of memory) counts as leaking.
function Leaks([string]$path) {
    try { return (ScanBytes ([IO.File]::ReadAllBytes($path))) } catch { return $true }
}
function LeaksBytes([byte[]]$bytes) {
    try { return (ScanBytes $bytes) } catch { return $true }
}
function ScanBytes([byte[]]$bytes) {
    if (HitBytes $bytes) { return $true }
    foreach ($marker in 0x78, 0x1F, 0x50) {
        $i = [Array]::IndexOf($bytes, [byte]$marker)
        while ($i -ge 0 -and $i -lt $bytes.Length - 30) {
            $at = StreamStart $bytes $i
            if ($at -gt 0 -and $at -lt $bytes.Length) {
                $inner = Inflate $bytes $at
                if ($null -ne $inner -and (HitBytes $inner)) { return $true }
            }
            $i = [Array]::IndexOf($bytes, [byte]$marker, $i + 1)
        }
    }
    return $false
}

# A STEP file's header names the folder it was exported to and often the person: FILE_NAME('<path>', time,
# (author), (organization), preprocessor, system, authorization). The copy that goes in the zip carries the bare file
# name, 'Fixture Builder' as author and no organization or authorization.
function CleanStep([byte[]]$bytes, [string]$bareName) {
    $latin = [Text.Encoding]::GetEncoding(28591)
    $q = "'(?:[^']|'')*'"
    $list = '\(\s*(?:' + $q + '\s*(?:,\s*' + $q + '\s*)*)?\)'
    $pattern = 'FILE_NAME\s*\(\s*' + $q + '\s*,\s*(' + $q + ')\s*,\s*' + $list + '\s*,\s*' + $list + '\s*,\s*(' + $q + ')\s*,\s*(' + $q + ')\s*,\s*' + $q + '\s*\)'
    $replacement = "FILE_NAME('" + $bareName.Replace("'", "''").Replace('$', '$$') + "',`$1,('Fixture Builder'),(''),`$2,`$3,'')"
    return ,$latin.GetBytes([regex]::Replace($latin.GetString($bytes), $pattern, $replacement, 'IgnoreCase'))
}
